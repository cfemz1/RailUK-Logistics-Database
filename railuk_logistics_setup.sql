-- 4. Create shipment trigger

CREATE OR REPLACE EDITIONABLE TRIGGER "TRG_SHIPMENT_BI" 
BEFORE INSERT ON Shipment
FOR EACH ROW
BEGIN
  
  IF :NEW.ShipmentID IS NULL THEN
    :NEW.ShipmentID := SEQ_SHIPMENT.NEXTVAL;
  END IF;

  
  IF :NEW.WeightKg <= 0 THEN
    RAISE_APPLICATION_ERROR(-20001, 'Shipment weight must be greater than zero.');
  END IF;


  IF :NEW.Status IS NULL THEN
    :NEW.Status := 'PLANNED';
  END IF;

 
  IF :NEW.CreatedDT IS NULL THEN
    :NEW.CreatedDT := SYSDATE;
  END IF;
END;
/
ALTER TRIGGER "TRG_SHIPMENT_BI" ENABLE;
